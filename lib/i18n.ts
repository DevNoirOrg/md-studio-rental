export const locales = ["hu", "en"] as const;
export type Locale = (typeof locales)[number];

export const isLocale = (value: unknown): value is Locale => value === "hu" || value === "en";

/** Intl formázókhoz: magyarul hu-HU, angolul brit angol (nap, hónap, év sorrend). */
export const intlLocale = (locale: Locale) => (locale === "en" ? "en-GB" : "hu-HU");

/** A basePath NÉLKÜLI útvonalak (a next/link hozzáteszi; sima <a>-hoz withBase kell). */
export const homePath = (locale: Locale) => (locale === "en" ? "/en" : "/");
export const privacyPath = (locale: Locale) => (locale === "en" ? "/en/privacy" : "/adatkezeles");

/** A nyelvváltó célja: ugyanaz az oldal a másik nyelven. */
export function alternatePath(pathname: string, locale: Locale): string {
  if (locale === "hu") return pathname.startsWith("/adatkezeles") ? "/en/privacy" : "/en";
  return pathname.startsWith("/en/privacy") ? "/adatkezeles" : "/";
}

